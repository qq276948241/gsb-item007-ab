def 跑一条(名称, 文本, 着法, 期望码, 期望出, 期望错):
    with tempfile.TemporaryDirectory(prefix="zouzi-check-") as 临时目录:
        (Path(临时目录) / "局面").write_text(文本, encoding="utf-8")
        参数 = [str(数) for 数 in 着法]
        进程 = subprocess.run(
            [sys.executable, str(走子脚本), *参数],
            cwd=临时目录,
            capture_output=True,
        )
    实际出 = 进程.stdout.decode("utf-8")
    实际错 = 进程.stderr.decode("utf-8")
    问题 = []
    if 进程.returncode != 期望码:
        问题.append("退出状态期望 %s 实际 %s" % (期望码, 进程.returncode))
    if 实际出 != 期望出:
        问题.append("stdout 期望 %r 实际 %r" % (期望出, 实际出))
    if 实际错 != 期望错:
        问题.append("stderr 期望 %r 实际 %r" % (期望错, 实际错))
    return 问题


def main():
    开局 = 局面文件.read_text(encoding="utf-8")
    跑前 = hashlib.sha256(开局.encode("utf-8")).hexdigest()

    用例 = 建用例(开局)
    明细 = []
    通过数 = 0
    合法数 = 0
    非法数 = 0
    for 条 in 用例:
        名称, 文本, 着法, 期望码, 期望出, 期望错 = 条
        if 期望码 == 0:
            合法数 += 1
        else:
            非法数 += 1
        问题 = 跑一条(*条)
        if 问题:
            明细.append((名称, 着法, 问题))
        else:
            通过数 += 1

    跑后文本 = 局面文件.read_text(encoding="utf-8")
    跑后 = hashlib.sha256(跑后文本.encode("utf-8")).hexdigest()
    局面一致 = 跑前 == 跑后

    行 = []
    行.append("走子脚本检查结果")
    行.append("生成时间：%s" % datetime.now().strftime("%Y-%m-%d %H:%M:%S"))
    行.append("被检查脚本：%s" % 走子脚本.name)
    行.append("用例总数：%d，通过：%d，失败：%d" % (len(用例), 通过数, len(用例) - 通过数))
    行.append("其中合法着法 %d 条，非法着法 %d 条" % (合法数, 非法数))
    行.append("局面文件 sha256 跑前：%s" % 跑前)
    行.append("局面文件 sha256 跑后：%s" % 跑后)
    行.append("局面文件与跑之前一致：%s" % ("是" if 局面一致 else "否"))
    if 明细:
        行.append("失败明细：")
        for 名称, 着法, 问题 in 明细:
            行.append("- %s（着法 %s）" % (名称, " ".join(str(数) for 数 in 着法)))
            for 一句 in 问题:
                行.append("    %s" % 一句)
    else:
        行.append("失败明细：无，全部通过。")

    报告 = "\n".join(行) + "\n"
    结果文件.write_text(报告, encoding="utf-8")
    print(报告)
    return 0 if 通过数 == len(用例) and 局面一致 else 1


if __name__ == "__main__":
    sys.exit(main())
