def 摆盘(边, 子力):
    盘 = [[空] * 9 for _ in range(10)]
    for (行号, 列号), 子 in 子力.items():
        盘[行号][列号] = 子
    return "\n".join([边] + ["".join(行) for 行 in 盘]) + "\n"


