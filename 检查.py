def 跑用例(局面文本, 着法):
    if 局面文本 is None:
        局面路径.write_bytes(原始局面)
    else:
        局面路径.write_text(局面文本, encoding="utf-8")
    结果 = subprocess.run(
        [sys.executable, str(脚本路径)] + [str(数) for 数 in 着法],
        cwd=str(目录),
        capture_output=True,
        text=True,
    )
    return 结果.returncode, 结果.stdout, 结果.stderr


def 主():
    明细 = []
    通过数 = 0
    try:
        for 名称, 局面文本, 着法, 期望码, 期望出, 期望错 in 用例:
            码, 出, 错 = 跑用例(局面文本, 着法)
            if (码, 出, 错) == (期望码, 期望出, 期望错):
                通过数 += 1
                明细.append("[通过] %s: 着法 %s, 退出码 %d" % (名称, 着法, 码))
            else:
                明细.append(
                    "[失败] %s: 着法 %s\n"
                    "    期望: 退出码 %d, 标准输出 %r, 标准错误 %r\n"
                    "    实际: 退出码 %d, 标准输出 %r, 标准错误 %r"
                    % (名称, 着法, 期望码, 期望出, 期望错, 码, 出, 错)
                )
    finally:
        局面路径.write_bytes(原始局面)
    局面一致 = 局面路径.read_bytes() == 原始局面
    失败数 = len(用例) - 通过数
    报告行 = [
        "走子.py 自动检查结果",
        "总用例: %d" % len(用例),
        "通过: %d" % 通过数,
        "失败: %d" % 失败数,
        "局面文件: %s" % ("跑后与跑之前一致" if 局面一致 else "跑后被改动,已恢复"),
        "",
        "明细:",
    ]
    报告行.extend(明细)
    报告 = "\n".join(报告行) + "\n"
    报告路径.write_text(报告, encoding="utf-8")
    sys.stdout.write(报告)
    return 0 if 失败数 == 0 and 局面一致 else 1


原始局面 = 局面路径.read_bytes()

if __name__ == "__main__":
    sys.exit(主())
