def 布子(边, 放置, 帅位=(9, 4), 将位=(0, 3)):
    盘 = [[空位 for _ in range(9)] for _ in range(10)]
    盘[帅位[0]][帅位[1]] = "帅"
    盘[将位[0]][将位[1]] = "將"
    for (行号, 列号), 子 in 放置.items():
        盘[行号][列号] = 子
    return 边 + "\n" + "\n".join("".join(行) for 行 in 盘) + "\n"


